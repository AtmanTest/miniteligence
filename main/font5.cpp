uint8_t font5_code(uint32_t cp)
{
    int lo = 0, hi = FONT5_N - 1;
    if (cp > 0xffff) return 0;
    while (lo <= hi) {
        int m = (lo + hi) / 2;
        if (FONT5_INDEX[m].cp == cp) return FONT5_INDEX[m].idx;
        if (FONT5_INDEX[m].cp < cp) lo = m + 1; else hi = m - 1;
    }
    return 0;
}

